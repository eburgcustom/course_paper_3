"""
Главный модуль приложения для работы с вакансиями с hh.ru.

Этот модуль инициализирует базу данных и запускает пользовательский интерфейс.
"""

def main():
    """
    Точка входа в приложение.

    Инициализирует базу данных и запускает главное меню.
    """
    print("Инициализация базы данных...")
    try:
        # Импорты внутри функции, чтобы избежать циклических импортов
        from src.database import init_db
        from src.cli.main_menu import MainMenu

        # Инициализация базы данных
        init_db.init_database()

        # Запуск главного меню
        menu = MainMenu()
        menu.run()

    except Exception as e:
        print(f"Произошла ошибка при инициализации приложения: {e}")
        input("Нажмите Enter для выхода...")


if __name__ == "__main__":
    main()
